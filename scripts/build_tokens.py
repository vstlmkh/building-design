#!/usr/bin/env python3
"""Compile DTCG design tokens into per-platform artifacts.

Reads  <design>/tokens/*.tokens.json  (primitives, semantic, components)
Writes <design>/tokens/build/{tokens.css,tokens.ts,tokens.dart,Tokens.swift,Tokens.kt,colors.xml}
and copies tokens.css into <design>/prototype/styles/ so the prototype never drifts.

Per-theme values live in  $extensions.themes.<theme>  on a token; the base $value is the
default theme. Aliases are "{dot.path}" and may chain.

Exit codes: 0 ok · 1 unresolved alias / malformed tokens · 2 bad usage
"""
import argparse
import json
import re
import sys
from pathlib import Path

ALIAS = re.compile(r"^\{([^}]+)\}$")


def load_tokens(tokens_dir: Path):
    """Merge every *.tokens.json into one tree. Later files win on conflict."""
    tree, extensions = {}, {}
    files = sorted(tokens_dir.glob("*.tokens.json"))
    if not files:
        raise SystemExit(f"ERROR: no *.tokens.json in {tokens_dir}")
    for f in files:
        try:
            data = json.loads(f.read_text())
        except json.JSONDecodeError as e:
            raise SystemExit(f"ERROR: {f}: invalid JSON: {e}")
        extensions.update(data.pop("$extensions", {}))
        deep_merge(tree, data)
    return tree, extensions


def deep_merge(dst, src):
    for k, v in src.items():
        if isinstance(v, dict) and isinstance(dst.get(k), dict):
            deep_merge(dst[k], v)
        else:
            dst[k] = v


def flatten(tree, prefix=()):
    """-> {dot.path: token_dict}. A node with $value is a token; otherwise a group."""
    out = {}
    for k, v in tree.items():
        if k.startswith("$"):
            continue
        if isinstance(v, dict) and "$value" in v:
            out[".".join(prefix + (k,))] = v
        elif isinstance(v, dict):
            out.update(flatten(v, prefix + (k,)))
    return out


def resolve(flat, theme, path, seen=None):
    """Resolve a token's value for a theme, following {aliases}. Raises on cycles/misses."""
    seen = seen or set()
    if path in seen:
        raise SystemExit(f"ERROR: alias cycle at '{path}'")
    tok = flat.get(path)
    if tok is None:
        raise SystemExit(f"ERROR: unresolved token reference '{path}'")
    val = tok.get("$extensions", {}).get("themes", {}).get(theme, tok["$value"])
    m = ALIAS.match(str(val).strip())
    if m:
        return resolve(flat, theme, m.group(1), seen | {path})
    return val


def themes_present(flat, declared):
    found = set()
    for t in flat.values():
        found |= set(t.get("$extensions", {}).get("themes", {}))
    return [d for d in declared if d == declared[0] or d in found]


def var_name(path, sep="-"):
    return sep.join(path.split("."))


def camel(path):
    parts = re.split(r"[.\-]", path)
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def pascal(path):
    return "".join(p.capitalize() for p in re.split(r"[.\-]", path))


def is_color(tok):
    return tok.get("$type") == "color"


def hex_to_argb(h):
    h = h.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    if len(h) == 6:
        h = "FF" + h.upper()
    elif len(h) == 8:  # #RRGGBBAA -> AARRGGBB
        h = (h[6:8] + h[0:6]).upper()
    return "0x" + h


def dim(v):
    """'16px' -> 16.0 ; returns None when not a plain pixel dimension."""
    m = re.fullmatch(r"(-?\d+(?:\.\d+)?)px", str(v).strip())
    return float(m.group(1)) if m else None


# --- emitters --------------------------------------------------------------
def emit_css(flat, themes, default_theme):
    lines = ["/* GENERATED by build_tokens.py — do not edit. */", ":root {"]
    for p in flat:
        lines.append(f"  --{var_name(p)}: {resolve(flat, default_theme, p)};")
    lines.append("}")
    for t in themes:
        if t == default_theme:
            continue
        lines += [f'\n[data-theme="{t}"] {{']
        for p in flat:
            v, d = resolve(flat, t, p), resolve(flat, default_theme, p)
            if v != d:
                lines.append(f"  --{var_name(p)}: {v};")
        lines.append("}")
        # First-load default before JS runs; the explicit attribute above still wins.
        lines += [f"\n@media (prefers-color-scheme: {t}) {{", "  :root:not([data-theme]) {"]
        for p in flat:
            v, d = resolve(flat, t, p), resolve(flat, default_theme, p)
            if v != d:
                lines.append(f"    --{var_name(p)}: {v};")
        lines += ["  }", "}"]
    return "\n".join(lines) + "\n"


def emit_ts(flat, themes, default_theme):
    out = ["// GENERATED by build_tokens.py — do not edit.",
           "export const tokens = {"]
    for t in themes:
        out.append(f"  {json.dumps(t)}: {{")
        for p in flat:
            out.append(f"    {json.dumps(p)}: {json.dumps(str(resolve(flat, t, p)))},")
        out.append("  },")
    out += ["} as const;", "",
            f"export type Theme = keyof typeof tokens;",
            "export type TokenPath = keyof (typeof tokens)[Theme];",
            f"export const defaultTheme: Theme = {json.dumps(default_theme)};"]
    return "\n".join(out) + "\n"


def emit_dart(flat, themes, default_theme):
    out = ["// GENERATED by build_tokens.py — do not edit.", "import 'dart:ui';", ""]
    for t in themes:
        cls = "AppColors" + ("" if t == default_theme else pascal(t))
        out.append(f"class {cls} {{")
        for p, tok in flat.items():
            if is_color(tok):
                v = resolve(flat, t, p)
                if str(v).startswith("#"):
                    out.append(f"  static const {camel(p)} = Color({hex_to_argb(v)});")
        out += ["}", ""]
    out.append("class AppSpace {")
    for p, tok in flat.items():
        d = dim(resolve(flat, default_theme, p))
        if d is not None and p.startswith(("space.", "radius.", "size.")):
            out.append(f"  static const {camel(p)} = {d};")
    out += ["}", ""]
    out.append("class AppMotion {")
    for p, tok in flat.items():
        if tok.get("$type") == "duration":
            ms = re.fullmatch(r"(\d+)ms", str(resolve(flat, default_theme, p)))
            if ms:
                out.append(f"  static const {camel(p)} = Duration(milliseconds: {ms.group(1)});")
    out.append("}")
    return "\n".join(out) + "\n"


def emit_swift(flat, themes, default_theme):
    out = ["// GENERATED by build_tokens.py — do not edit.", "import SwiftUI", "",
           "public enum Tokens {"]
    for t in themes:
        out.append(f"  public enum {pascal(t)} {{")
        for p, tok in flat.items():
            if is_color(tok):
                v = str(resolve(flat, t, p))
                if v.startswith("#"):
                    h = v.lstrip("#")
                    if len(h) == 3:
                        h = "".join(c * 2 for c in h)
                    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
                    out.append(f"    public static let {camel(p)} = Color(red: {r:.4f}, "
                               f"green: {g:.4f}, blue: {b:.4f})")
        out.append("  }")
    out.append("  public enum Space {")
    for p in flat:
        d = dim(resolve(flat, default_theme, p))
        if d is not None and p.startswith(("space.", "radius.", "size.")):
            out.append(f"    public static let {camel(p)}: CGFloat = {d}")
    out += ["  }", "}"]
    return "\n".join(out) + "\n"


def emit_kotlin(flat, themes, default_theme):
    out = ["// GENERATED by build_tokens.py — do not edit.", "package design.tokens", "",
           "import androidx.compose.ui.graphics.Color", "import androidx.compose.ui.unit.dp", ""]
    for t in themes:
        out.append(f"object AppColors{pascal(t)} {{")
        for p, tok in flat.items():
            if is_color(tok):
                v = str(resolve(flat, t, p))
                if v.startswith("#"):
                    out.append(f"    val {camel(p)} = Color({hex_to_argb(v)})")
        out += ["}", ""]
    out.append("object AppSpace {")
    for p in flat:
        d = dim(resolve(flat, default_theme, p))
        if d is not None and p.startswith(("space.", "radius.", "size.")):
            out.append(f"    val {camel(p)} = {d}.dp")
    out.append("}")
    return "\n".join(out) + "\n"


def emit_colors_xml(flat, theme):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           "<!-- GENERATED by build_tokens.py — do not edit. -->", "<resources>"]
    for p, tok in flat.items():
        if is_color(tok):
            v = str(resolve(flat, theme, p))
            if v.startswith("#"):
                out.append(f'    <color name="{var_name(p, "_")}">{v}</color>')
    out.append("</resources>")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("design", nargs="?", default="design", help="path to the design/ workspace")
    ap.add_argument("--check", action="store_true",
                    help="resolve and validate only; write nothing (use in CI)")
    a = ap.parse_args(argv)

    design = Path(a.design).resolve()
    if not design.is_dir():
        print(f"ERROR: not a directory: {design}", file=sys.stderr)
        return 2
    cfg_path = design / "design.config.json"
    cfg = json.loads(cfg_path.read_text()) if cfg_path.exists() else {}
    declared = cfg.get("themes", ["light", "dark"])
    default_theme = cfg.get("defaultTheme", declared[0])
    platforms = cfg.get("platforms", ["web", "ios", "android"])

    tree, _ = load_tokens(design / cfg.get("paths", {}).get("tokens", "tokens"))
    flat = flatten(tree)
    if not flat:
        print("ERROR: token files contain no tokens ($value nodes)", file=sys.stderr)
        return 1
    themes = themes_present(flat, declared)
    for t in themes:  # fail fast on broken aliases, before writing anything
        for p in flat:
            resolve(flat, t, p)

    if a.check:
        print(f"OK: {len(flat)} tokens resolve in themes: {', '.join(themes)}")
        return 0

    out_dir = design / "tokens" / "build"
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []

    def put(name, text):
        (out_dir / name).write_text(text)
        written.append(name)

    css = emit_css(flat, themes, default_theme)
    put("tokens.css", css)
    if "web" in platforms:
        put("tokens.ts", emit_ts(flat, themes, default_theme))
    if "ios" in platforms:
        put("Tokens.swift", emit_swift(flat, themes, default_theme))
    if "android" in platforms:
        put("Tokens.kt", emit_kotlin(flat, themes, default_theme))
        put("colors.xml", emit_colors_xml(flat, default_theme))
        for t in themes:
            if t != default_theme:
                put(f"colors-{t}.xml", emit_colors_xml(flat, t))
    # Flutter is a web/mobile-agnostic target; emit when any mobile platform is declared.
    if {"ios", "android"} & set(platforms):
        put("tokens.dart", emit_dart(flat, themes, default_theme))

    # The prototype reads this copy; keeping it in sync is what stops design/code drift.
    proto_styles = design / cfg.get("paths", {}).get("prototype", "prototype") / "styles"
    if proto_styles.is_dir():
        (proto_styles / "tokens.css").write_text(css)
        written.append("-> prototype/styles/tokens.css")

    print(f"Built {len(flat)} tokens x {len(themes)} themes ({', '.join(themes)})")
    for w in written:
        print(f"  {w}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
